CVI_U8 sc535hai_i2c_addr = 0x30;        /* I2C Address of SC535HAI */
const CVI_U32 sc535hai_addr_byte = 2;
const CVI_U32 sc535hai_data_byte = 1;

int sc535hai_i2c_init(VI_PIPE ViPipe)
{
	return sensor_i2c_init(ViPipe, (CVI_U8)g_aunSC535HAI_BusInfo[ViPipe].s8I2cDev,
							(CVI_U8)g_aunSC535HAI_AddrInfo[ViPipe].s8I2cAddr);
}

int sc535hai_i2c_exit(VI_PIPE ViPipe)
{
	return sensor_i2c_exit(ViPipe, (CVI_U8)g_aunSC535HAI_BusInfo[ViPipe].s8I2cDev);
}

int sc535hai_read_register(VI_PIPE ViPipe, int addr)
{
	return sensor_i2c_read(ViPipe, (CVI_U8)g_aunSC535HAI_BusInfo[ViPipe].s8I2cDev,
							(CVI_U8)g_aunSC535HAI_AddrInfo[ViPipe].s8I2cAddr, (CVI_U32)addr,
							sc535hai_addr_byte, sc535hai_data_byte);
}

int sc535hai_write_register(VI_PIPE ViPipe, int addr, int data)
{
	return sensor_i2c_write(ViPipe, (CVI_U8)g_aunSC535HAI_BusInfo[ViPipe].s8I2cDev,
							(CVI_U8)g_aunSC535HAI_AddrInfo[ViPipe].s8I2cAddr, (CVI_U32)addr,
							sc535hai_addr_byte, (CVI_U32)data, sc535hai_data_byte);
}

static void delay_ms(int ms)
{
	usleep(ms * 1000);
}

void sc535hai_standby(VI_PIPE ViPipe)
{
	sc535hai_write_register(ViPipe, 0x0100, 0x00);
}

void sc535hai_restart(VI_PIPE ViPipe)
{
	sc535hai_write_register(ViPipe, 0x0100, 0x00);
	delay_ms(20);
	sc535hai_write_register(ViPipe, 0x0100, 0x01);
}

void sc535hai_default_reg_init(VI_PIPE ViPipe)
{
	CVI_U32 i;

	for (i = 0; i < g_pastSC535HAI[ViPipe]->astSyncInfo[0].snsCfg.u32RegNum; i++) {
		sc535hai_write_register(ViPipe,
				g_pastSC535HAI[ViPipe]->astSyncInfo[0].snsCfg.astI2cData[i].u32RegAddr,
				g_pastSC535HAI[ViPipe]->astSyncInfo[0].snsCfg.astI2cData[i].u32Data);
	}
}

#define SC535HAI_CHIP_ID_HI_ADDR		0x3107
#define SC535HAI_CHIP_ID_LO_ADDR		0x3108
#define SC535HAI_CHIP_ID			0xce78

void sc535hai_mirror_flip(VI_PIPE ViPipe, ISP_SNS_MIRRORFLIP_TYPE_E eSnsMirrorFlip)
{
	CVI_U8 val = 0;

	switch (eSnsMirrorFlip) {
	case ISP_SNS_NORMAL:
		break;
	case ISP_SNS_MIRROR:
		val |= 0x6;
		break;
	case ISP_SNS_FLIP:
		val |= 0x60;
		break;
	case ISP_SNS_MIRROR_FLIP:
		val |= 0x66;
		break;
	default:
		return;
	}

	sc535hai_write_register(ViPipe, 0x3221, val);
}

int sc535hai_probe(VI_PIPE ViPipe)
{
	int nVal;
	CVI_U16 chip_id;

	delay_ms(4);
	if (sc535hai_i2c_init(ViPipe) != CVI_SUCCESS)
		return CVI_FAILURE;

	nVal = sc535hai_read_register(ViPipe, SC535HAI_CHIP_ID_HI_ADDR);
	if (nVal < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "read sensor id error.\n");
		return nVal;
	}
	chip_id = (nVal & 0xFF) << 8;
	nVal = sc535hai_read_register(ViPipe, SC535HAI_CHIP_ID_LO_ADDR);
	if (nVal < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "read sensor id error.\n");
		return nVal;
	}
	chip_id |= (nVal & 0xFF);

	if (chip_id != SC535HAI_CHIP_ID) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "Sensor ID Mismatch! Use the wrong sensor??\n");
		return CVI_FAILURE;
	}

	return CVI_SUCCESS;
}


void sc535hai_init(VI_PIPE ViPipe)
{
	CVI_U8 u8ImgMode = g_pastSC535HAI[ViPipe]->u8ImgMode;

	sc535hai_i2c_init(ViPipe);

	if (u8ImgMode == SC535HAI_MODE_1920P30_4L_MASTER)
		sc535hai_linear_1920p30_4l_master_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P30_4L_SLAVE)
		sc535hai_linear_1920p30_4l_slave_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P30_2L_MASTER)
		sc535hai_linear_1920p30_2l_master_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P30_2L_SLAVE)
		sc535hai_linear_1920p30_2l_slave_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P15_4L_MASTER)
		sc535hai_linear_1920p15_4l_master_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P15_4L_SLAVE)
		sc535hai_linear_1920p15_4l_slave_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P15_2L_MASTER)
		sc535hai_linear_1920p15_2l_master_init(ViPipe);
	else if (u8ImgMode == SC535HAI_MODE_1920P15_2L_SLAVE)
		sc535hai_linear_1920p15_2l_slave_init(ViPipe);

	g_pastSC535HAI[ViPipe]->bInit = CVI_TRUE;
}


