bool reg_scan_read(uint32_t offset, hdmi_tx_dev_t dev_t, uint32_t read_value){
	uint32_t data = 0;

	data = dev_read(&dev_t, offset);

	if(data == 0){
		LOGGER(SNPS_ERROR, "Read reg error");
		return false;
	}

	if(data == read_value){
		printf("PASSED!, Reset Value:%x, Actual Value:%x\n", read_value, data);
	}
	else{
		printf("***************FAILED***************, Reset Value:%x, Actual Value:%x\n", read_value, data);
		return false;
	}

	return true;
}

void reg_scan_write(uint32_t offset, hdmi_tx_dev_t dev_t, uint32_t write_value){

    dev_write(&dev_t, offset, write_value);

	return;
}

void reg_read_write(uint32_t reg_name,
               hdmi_tx_dev_t dev_t,
			   uint32_t read_value_defaule,
			   uint32_t read_value_0,
			   uint32_t read_value_1,
			   uint32_t write_value_0,
			   uint32_t write_value_1){

	//read default reg value
	reg_scan_read(reg_name, dev_t, read_value_defaule);
	//write 0x00 then read
	reg_scan_write(reg_name, dev_t, write_value_0);
	reg_scan_read(reg_name, dev_t, read_value_0);
	//write 0xff then read
	reg_scan_write(reg_name, dev_t, write_value_1);
	reg_scan_read(reg_name, dev_t, read_value_1);

	return;
}

void reg_scan(hdmi_tx_dev_t dev_t){

	for(int i=0; reg_cfg[i].reg_name !=END_FLAG; i++){

		if(reg_cfg[i].reg_name == HDCP_KSV){

			for(int j=0; j<=634; j++){
				reg_read_write(reg_cfg[i].reg_name + j*4,
								dev_t,
								reg_cfg[i].read_value_defaule,
								reg_cfg[i].read_value_0,
								reg_cfg[i].read_value_0,
								reg_cfg[i].write_value_0,
								reg_cfg[i].write_value_1);
			}
		}
		else if(reg_cfg[i].reg_name == HDCP_REVOC_LIST){
			for(int k=0; k<=5059; k++){
				reg_read_write(reg_cfg[i].reg_name + k*4,
								dev_t,
								reg_cfg[i].read_value_defaule,
								reg_cfg[i].read_value_0,
								reg_cfg[i].read_value_0,
								reg_cfg[i].write_value_0,
								reg_cfg[i].write_value_1);
			}
		}
		else{
			reg_read_write(reg_cfg[i].reg_name,
							dev_t,
							reg_cfg[i].read_value_defaule,
							reg_cfg[i].read_value_0,
							reg_cfg[i].read_value_0,
							reg_cfg[i].write_value_0,
							reg_cfg[i].write_value_1);

		}
	}
	return;
}